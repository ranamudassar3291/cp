export function findCountryOption(countryCodeOrName?: string): CountryRegionOption {
  const query = (countryCodeOrName || '').trim().toLowerCase();
  if (!query) return WORLD_COUNTRIES[0];
  return (
    WORLD_COUNTRIES.find(
      (c) =>
        c.code.toLowerCase() === query ||
        c.name.toLowerCase() === query ||
        c.name.toLowerCase().includes(query)
    ) ?? WORLD_COUNTRIES[0]
  );
}

export function getStatesForCountry(countryCodeOrName?: string): string[] {
  const matched = findCountryOption(countryCodeOrName);
  return matched.states;
}
