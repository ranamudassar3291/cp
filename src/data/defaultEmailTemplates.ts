export function renderEmailMergeText(
  text: string,
  overrides?: Record<string, string>
): string {
  const vars = { ...SAMPLE_EMAIL_MERGE_DATA, ...(overrides || {}) };
  return text.replace(/\{\{\s*([a-zA-Z0-9_]+)\s*\}\}/g, (_match, key: string) => {
    return vars[key] ?? `{{${key}}}`;
  });
}

